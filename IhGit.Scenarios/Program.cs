using IhGit.Core.Scenarios;

const string usage = """
    IhGit scenario generator

      list                          List available scenarios
      create <name> [directory]     Create a scenario (default: %TEMP%\IhGitScenarios\<name>-<timestamp>)
      delete <directory>            Delete a generated scenario (refuses anything not generated by this tool)
      create-all [directory]        Create every scenario below a new directory
    """;

try
{
    switch (args)
    {
        case ["list"]:
            foreach (var scenario in ScenarioBuilder.Catalog)
                Console.WriteLine($"{scenario.Name,-36} {scenario.Description}");
            return 0;

        case ["create", var name]:
            return Create(name, DefaultDirectory(name));

        case ["create", var name, var directory]:
            return Create(name, directory);

        case ["create-all"]:
            return CreateAll(DefaultDirectory("all"));

        case ["create-all", var directory]:
            return CreateAll(directory);

        case ["delete", var directory]:
            ScenarioGuard.Delete(directory);
            Console.WriteLine($"Deleted {Path.GetFullPath(directory)}");
            return 0;

        default:
            Console.WriteLine(usage);
            return args.Length == 0 ? 0 : 1;
    }
}
catch (ScenarioValidationException ex)
{
    Console.Error.WriteLine(ex.Message);
    return 2;
}

static string DefaultDirectory(string name)
    => Path.Combine(Path.GetTempPath(), "IhGitScenarios", $"{name}-{DateTime.Now:yyyyMMddHHmmss}");

static int Create(string name, string directory)
{
    var manifest = ScenarioBuilder.Create(name, directory);

    Console.WriteLine($"Scenario '{name}' created: {manifest.DirectoryPath}");
    Console.WriteLine($"  working clone : {manifest.RepoPath}");
    Console.WriteLine($"  local origin  : {manifest.OriginPath}");
    Console.WriteLine($"  expected      : {manifest.ExpectedFirstOutcome} on the first target");
    Console.WriteLine();
    Console.WriteLine("Open it in the WPF app with:");
    Console.WriteLine($"  IhGitWpf.exe --offline-scenario \"{Path.Combine(manifest.DirectoryPath, ScenarioManifest.FileName)}\"");
    return 0;
}

static int CreateAll(string directory)
{
    foreach (var scenario in ScenarioBuilder.Catalog)
        Create(scenario.Name, Path.Combine(directory, scenario.Name));

    return 0;
}
